(()=>{
  "use strict";

  // Keep only the single Tool Hub entry visible by default.
  // The pinned shelf remembers whether the user last opened it.
  const favoriteDisclosure=document.querySelector("#xySidebarFavDisclosure");
  const favoriteKey="xy.sidebar.favorites.expanded.v1";
  if(favoriteDisclosure){
    try{favoriteDisclosure.open=localStorage.getItem(favoriteKey)==="true"}catch{}
    favoriteDisclosure.addEventListener("toggle",()=>{
      try{localStorage.setItem(favoriteKey,String(favoriteDisclosure.open))}catch{}
    });
  }

  let observer=null,raf=0,activePanel=null;
  const $=(sel,root=document)=>root.querySelector(sel);

  function wrapSection(node,id,title,subtitle){
    if(!node||node.closest(".xy-tidy-disclosure"))return null;
    const details=document.createElement("details");
    details.className="xy-tidy-disclosure";
    details.dataset.tidy=id;

    const head=document.createElement("summary");
    head.className="xy-tidy-summary";
    const titleSpan=document.createElement("span");
    titleSpan.className="xy-tidy-title";
    titleSpan.textContent=title;
    const small=document.createElement("small");
    small.className="xy-tidy-subtitle";
    small.textContent=subtitle;
    const text=document.createElement("span");
    text.className="xy-tidy-label";
    text.append(titleSpan,small);
    const chevron=document.createElement("i");
    chevron.className="xy-tidy-chevron";
    chevron.setAttribute("aria-hidden","true");
    chevron.textContent="⌄";
    head.append(text,chevron);

    node.before(details);
    details.append(head,node);
    node.classList.add("xy-tidy-content");

    details.addEventListener("toggle",()=>{
      if(!details.open)return;
      const panel=$("#panelBody");
      for(const other of panel?.querySelectorAll("details.xy-tidy-disclosure, #xyVisionDisclosure")||[]){
        if(other!==details&&other.open)other.open=false;
      }
    });
    return {details,small};
  }

  function decorate(){
    const body=$("#panelBody");
    if(!body||!body.querySelector("#endpointList"))return;
    // Preserve the existing controls and their event handlers: move DOM, never rebuild it.
    const context=$("#xyContextMessageLimit",body);
    const contextCard=context?.closest(".xy-context-limit-setting");
    if(contextCard&&!contextCard.closest(".xy-tidy-disclosure")){
      const current=window.xyContextWindow?.readLimit?.();
      const item=wrapSection(contextCard,"context","上下文消息",current===0?"发送全部消息":"最近 "+(current||40)+" 条");
      const refresh=()=>{
        const n=window.xyContextWindow?.readLimit?.();
        if(item)item.small.textContent=n===0?"发送全部消息":"最近 "+(n||40)+" 条";
      };
      $("#xySaveContextLimit",contextCard)?.addEventListener("click",()=>queueMicrotask(refresh));
    }

    const heart=$("#xyHeartNotesToggle",body);
    const heartCard=heart?.closest(".xy-heart-setting");
    if(heartCard&&!heartCard.closest(".xy-tidy-disclosure")){
      const item=wrapSection(heartCard,"heart","心音胶囊",heart.checked?"已开启":"已关闭");
      heart.addEventListener("change",()=>{if(item)item.small.textContent=heart.checked?"已开启":"已关闭"});
    }

    const proactive=$("#xyProactiveSettings",body);
    if(proactive&&!proactive.closest(".xy-tidy-disclosure")){
      const status=$("#xyProactiveStatus",proactive);
      const item=wrapSection(proactive,"proactive","主动来电",status?.textContent?.trim()||"查看设置");
      $("#xyProactiveEnabled",proactive)?.addEventListener("change",()=>{
        requestAnimationFrame(()=>{if(item)item.small.textContent=status?.textContent?.trim()||"查看设置"});
      });
    }

    // Backup vision's own summary is generated by vision-fallback.js and already
    // defaults to collapsed. It is part of the same settings accordion.
    const vision=$("#xyVisionDisclosure",body);
    if(vision&&!vision.dataset.tidyBound){
      vision.dataset.tidyBound="1";
      vision.addEventListener("toggle",()=>{
        if(!vision.open)return;
        for(const other of body.querySelectorAll("details.xy-tidy-disclosure")){
          if(other.open)other.open=false;
        }
      });
    }
  }

  function scheduleDecorate(){
    if(raf)cancelAnimationFrame(raf);
    raf=requestAnimationFrame(()=>{raf=0;decorate()});
  }

  function observeSettings(){
    const body=$("#panelBody");
    if(!body||!body.querySelector("#endpointList"))return;
    if(activePanel===body&&observer)return;
    observer?.disconnect();
    activePanel=body;
    observer=new MutationObserver(mutations=>{
      // Watch only new top-level injected cards; wrapping a card in <details>
      // triggers one more observer delivery, but decorate() is idempotent.
      if(mutations.some(m=>m.addedNodes.length))scheduleDecorate();
    });
    observer.observe(body,{childList:true});
    scheduleDecorate();
  }

  const beforeOpen=openPanel;
  openPanel=function(type){
    if(type!=="settings"){
      observer?.disconnect();
      observer=null;
      activePanel=null;
      if(raf){cancelAnimationFrame(raf);raf=0}
    }
    const result=beforeOpen(type);
    if(type==="settings")observeSettings();
    return result;
  };
})();
